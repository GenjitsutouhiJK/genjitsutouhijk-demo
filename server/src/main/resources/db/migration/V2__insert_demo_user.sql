-- 为什么要专门插一个种子用户？
--   ① 别人把仓库 clone 下来、直接 mvn spring-boot:run，就能用 admin / 123456 登录看到效果，
--      不用先手动去注册一个账号；
--   ② 测试也靠它跑 —— 测试用独立的数据库，Flyway 会在测试库里把这个脚本再执行一遍，
--      所以测试和线上环境的"起点数据"完全一致，不会出现"我这儿能跑你那儿不行"。
--
-- ⚠️ 这一串哈希值是**公开**写在仓库里的。它只是个练手用的演示账号，
